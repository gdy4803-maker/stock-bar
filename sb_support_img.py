def scaled_to(photo, size: int):
    """把 PhotoImage 近似缩放到 size 像素(zoom/subsample 组合)。"""
    try:
        n = photo.width()
    except Exception:
        return photo
    size = int(size)
    if size <= 0 or size == n:
        return photo
    ratio = size / float(n)
    k = max(1, int(round(ratio * 32)))
    return photo.zoom(k, k).subsample(32, 32)
